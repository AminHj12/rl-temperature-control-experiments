% Selected Ranges
range_11 = 101;
range_12 = 500;
range_21 = 501;
range_22 = 900;
range_31 = 501;
range_32 = 900;
range_1 = range_12 - range_11 + 1;
range_2 = range_22 - range_21 + 1;
range_3 = range_32 - range_31 + 1;
% Read the CSV file and separate important values
data = readmatrix('Total_Data.csv');
total_err_11 = data(range_11, 2);
total_err_12 = data(range_12, 2);
total_err_21 = data(range_21, 2);
total_err_22 = data(range_22, 2);
total_err_31 = data(range_31, 2);
total_err_32 = data(range_32, 2);
total_el_11 = data(range_11, 6);
total_el_12 = data(range_12, 6);
total_el_21 = data(range_21, 6);
total_el_22 = data(range_22, 6);
total_el_31 = data(range_31, 6);
total_el_32 = data(range_32, 6);
total_fn_11 = data(range_11, 7);
total_fn_12 = data(range_12, 7);
total_fn_21 = data(range_21, 7);
total_fn_22 = data(range_22, 7);
total_fn_31 = data(range_31, 7);
total_fn_32 = data(range_32, 7);
total_ei_11 = data(range_11, 8);
total_ei_12 = data(range_12, 8);
total_ei_21 = data(range_21, 8);
total_ei_22 = data(range_22, 8);
total_ei_31 = data(range_31, 8);
total_ei_32 = data(range_32, 8);
% Calculate important values
delta_err_1 = total_err_12 - total_err_11;
delta_err_2 = total_err_22 - total_err_21;
delta_err_3 = total_err_32 - total_err_31;
delta_el_1 = total_el_12 - total_el_11;
delta_el_2 = total_el_22 - total_el_21;
delta_el_3 = total_el_32 - total_el_31;
delta_fn_1 = total_fn_12 - total_fn_11;
delta_fn_2 = total_fn_22 - total_fn_21;
delta_fn_3 = total_fn_32 - total_fn_31;
delta_ei_1 = total_ei_12 - total_ei_11;
delta_ei_2 = total_ei_22 - total_ei_21;
delta_ei_3 = total_ei_32 - total_ei_31;
avg_err_1 = delta_err_1 / range_1;
avg_err_2 = delta_err_2 / range_2;
avg_err_3 = delta_err_3 / range_3;
avg_ei_1 = delta_ei_1 / range_1;
avg_ei_2 = delta_ei_2 / range_2;
avg_ei_3 = delta_ei_3 / range_3;
energy_1 = (40 * delta_el_1 + 2 * delta_fn_1) / 360;
energy_2 = (40 * delta_el_2 + 2 * delta_fn_2) / 360;
energy_3 = (40 * delta_el_3 + 2 * delta_fn_3) / 360;
avg_pwr_1 = (40 * delta_el_1 + 2 * delta_fn_1) / range_1;
avg_pwr_2 = (40 * delta_el_2 + 2 * delta_fn_2) / range_2;
avg_pwr_3 = (40 * delta_el_3 + 2 * delta_fn_3) / range_3;
% Print the results
fprintf('Total Temperature Error (%i-%i): %f\n', range_11, range_12, delta_err_1);
fprintf('Total Temperature Error Average (%i-%i): %f\n', range_11, range_12, avg_err_1);
fprintf('Total Energy Index (%i-%i): %i\n', range_11, range_12, delta_ei_1);
fprintf('Total Energy Index Average (%i-%i): %f\n', range_11, range_12, avg_ei_1);
fprintf('Total Energy Consumption (%i-%i): %f\n', range_11, range_12, energy_1);
fprintf('Total Power Consumption Average (%i-%i): %f\n\n', range_11, range_12, avg_pwr_1);
fprintf('Total Temperature Error (%i-%i): %f\n', range_21, range_22, delta_err_2);
fprintf('Total Temperature Error Average (%i-%i): %f\n', range_21, range_22, avg_err_2);
fprintf('Total Energy Index (%i-%i): %i\n', range_21, range_22, delta_ei_2);
fprintf('Total Energy Index Average (%i-%i): %f\n', range_21, range_22, avg_ei_2);
fprintf('Total Energy Consumption (%i-%i): %f\n', range_21, range_22, energy_2);
fprintf('Total Power Consumption Average (%i-%i): %f\n\n', range_21, range_22, avg_pwr_2);
fprintf('Total Temperature Error (%i-%i): %f\n', range_31, range_32, delta_err_3);
fprintf('Total Temperature Error Average (%i-%i): %f\n', range_31, range_32, avg_err_3);
fprintf('Total Energy Index (%i-%i): %i\n', range_31, range_32, delta_ei_3);
fprintf('Total Energy Index Average (%i-%i): %f\n', range_31, range_32, avg_ei_3);
fprintf('Total Energy Consumption (%i-%i): %f\n', range_31, range_32, energy_3);
fprintf('Total Power Consumption Average (%i-%i): %f\n\n', range_31, range_32, avg_pwr_3);